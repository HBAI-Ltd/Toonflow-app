function roundHole(x: number, z: number, radius: number, count = 12): [number, number][] {
  return Array.from({ length: count }, (_, index) => {
    const angle = -index * Math.PI * 2 / count;
    return [x + Math.cos(angle) * radius, z + Math.sin(angle) * radius];
  });
}

