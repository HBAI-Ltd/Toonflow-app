// 殿用 whiteboxCompounds 的 hall()（开间 4.5m、进深间 3.0m），围墙、游廊沿用同一套；诡异、祭祀、族会类的戏都能直接搭。
const ch = folk("民俗", "中式", "民俗建筑");
type HO = Parameters<typeof hall>[1];
const H = (b: AB, cx: number, cz: number, rot: 0 | 90 | 180 | 270, bays: number, deep: number, o: Partial<HO> = {}) => hall(b, { cx, cz, rot, bays, deep, ...o });
/** 四面围墙：x0<x1、z0<z1，z1 是正面；gw>0 时正面中间留 gw 宽的缺口（门屋所在）。 */
const ring4 = (b: AB, x0: number, z0: number, x1: number, z1: number, h = 3.4, t = .5, gw = 0, gx = 0) => {
  fenceRun(b, x0, z0, x1, z0, h, t); fenceRun(b, x0, z0, x0, z1, h, t); fenceRun(b, x1, z0, x1, z1, h, t);
  if (gw > 0) { fenceRun(b, x0, z1, gx - gw / 2, z1, h, t); fenceRun(b, gx + gw / 2, z1, x1, z1, h, t); } else fenceRun(b, x0, z1, x1, z1, h, t);
};
/** 堂内神台：三级台阶式（高 0.3、0.6、0.9）加一排牌位，cz 是靠后墙的中心 z，y0 是台基面标高。 */
const dais = (b: AB, cz: number, y0: number, w: number, d: number) => {
  for (let k = 0; k < 3; k++) b.box("base", 0, y0 + (k + 1) * .15, cz, w - k * 1.2, (k + 1) * .3, d - k * .5);
  for (let i = 0; i < 9; i++) b.box("furn", (i - 4) * .55, y0 + 1.25, cz - d / 2 + .6, .28, .7, .06);
};
/** 门屋前的台基和踏步。 */
const stoop = (b: AB, w: number, z0: number, z1: number, h: number) => { b.base(-w / 2, z0, w / 2, z1, h); b.steps(0, z1, "+z", 3, h); };
/** 旗杆：石座加杆。 */
const pole = (b: AB, x: number, z: number, h = 13) => { b.box("base", x, .4, z, 1.2, .8, 1.2); b.cyl("struct", x, z, .8, h, .14, 8); };
/** 蹲狮：须弥座、身、头。 */
const lion = (b: AB, x: number, z: number) => { b.box("base", x, .35, z, 1.1, .7, 1.4); b.box("base", x, 1.1, z, .8, .8, 1); b.sphere("base", [x, 1.75, z + .15], .36); };
/** 二层殿：下层 ch1 高、上层 ch2 高、硬山屋面；返回屋檐标高。 */
const twoStorey = (b: AB, cx: number, cz: number, bays: number, deep: number, ph: number, ch1: number, ch2: number, roof: HO["roof"] = "hard") => {
  const W = bays * 4.5, D = deep * 3, ys = ph + ch1 + .2;
  H(b, cx, cz, 0, bays, deep, { ph, ch: ch1, roof: "none", t: .4 }); b.slab(cx - W / 2, cz - D / 2, cx + W / 2, cz + D / 2, ys, .3, undefined, "floor"); H(b, cx, cz, 0, bays, deep, { plat: false, y0: ys, ch: ch2, roof, t: .4 });
  return ys + ch2;
};

